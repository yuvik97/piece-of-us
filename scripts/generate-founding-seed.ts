// Writes supabase/seed_founding.sql from the deterministic Founding Collection layout.
import { writeFileSync } from "fs";
import { generateFounding } from "../src/lib/founding/layout";

const rows = generateFounding();
const chunks: string[] = [];
for (let i = 0; i < rows.length; i += 1000) {
  const vals = rows.slice(i, i + 1000).map((r) => `(${r.tile},${r.kind},${r.seed},${r.palette})`).join(",\n");
  chunks.push(`insert into public.founding_pieces (tile, kind, seed, palette) values\n${vals}\non conflict (tile) do nothing;`);
}
const sql = `-- Founding Collection: ${rows.length} pieces, generated by scripts/generate-founding-seed.ts
begin;
${chunks.join("\n\n")}

insert into public.tile_claims (tile, kind)
select tile, 'founding' from public.founding_pieces where not hidden
on conflict (tile) do nothing;
commit;
`;
writeFileSync("supabase/seed_founding.sql", sql);
console.log(`wrote supabase/seed_founding.sql (${rows.length} pieces)`);
